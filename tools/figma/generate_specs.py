"""Generate editable, native Flutter screen specs from MCP design context.

Run prepare.mjs, download_assets.py and the local measurement preview first.
The shipped app uses Flutter widgets and local assets, never reference HTML.
"""
import collections
import hashlib
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
preview = ROOT / 'design_source/preview'
frames = json.loads((preview / 'measured_layout.json').read_text())
manifest = {s['id']: s for s in json.loads((preview / 'manifest.json').read_text())}
connections = json.loads((ROOT / 'design_source/prototype_connections.json').read_text())
aliases = {'230:1426': '230:1425', '763:235': '230:1093'}
names = {
 '403:2759':'Map', '292:3681':'Search locations', '292:3312':'Map filters',
 '292:3829':'Map legend', '403:2866':'Nearby reports', '562:828':'Report details',
 '403:3026':'Directions', '1358:343':'Volunteer notifications',
 '292:4283':'Fund & transparency', '292:4198':'Analytics & reports',
 '292:4022':'Report moderation', '605:523':'Volunteer applications',
 '614:766':'Volunteer application details', '689:327':'Accept report',
 '689:426':'Reject report', '692:477':'Admin overview', '692:816':'Review report',
 '722:6967':'Admin navigation', '1335:4001':'Become a volunteer',
 '1335:4104':'Application status', '1335:4347':'Volunteer application',
 '1335:4216':'Volunteer onboarding', '1335:4425':'Training: verify reports',
 '1335:4572':'Training: create events', '1335:4756':'Training: safety & rescue',
}
features = collections.defaultdict(list)
assets = {}
for frame in frames:
    spec = manifest[frame['id']]
    frame['feature'] = feature = spec['feature']
    frame['title'] = names.get(frame['id'], re.sub(r'^\d+_UI_|^Frame \d+ - |^D\d+ - |^\d+\. ', '', frame['name']).replace('_', ' '))
    frame['hotspots'] = []
    for screen, node, name, bounds, actions in connections:
        if screen != frame['id'] or not bounds:
            continue
        action = actions[0]
        target = aliases.get(action[1], action[1]) if len(action)>1 else None
        frame['hotspots'].append({'id':node,'name':name,'r':bounds,'type':action[0],'target':target,'navigation':action[2] if len(action)>2 else None})
    for e in frame['elements']:
        if e['type']=='image':
            path=ROOT/e['asset']
            if not path.exists() or not path.stat().st_size:
                raise RuntimeError(f'Missing asset: {path}')
            assets[e['asset']]={'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
    # Inputs are ordinary Flutter TextFields over the exact reference field slot.
    frame['fields']=[]
    for e in frame['elements']:
        if e['type']!='text' or e['nav']:
            continue
        text=e['text'].strip()
        is_placeholder=bool(re.match(r'^(Search |e\.g\.|eg\.|Enter |Type a message|Write a comment|Leave a note|Tell your neighbors|What made this|Brief share|Goals and activity|Write some memories)',text,re.I))
        explicit=frame['id']=='666:4366' and text in ['Hoan','imnothoan','Da Nang, Vietnam','Eco Explorer who loves weekend beach cleanups and sorting waste the right way.']
        if not is_placeholder and not explicit:
            continue
        x,y,w,h=e['r']
        boxes=[b for b in frame['elements'] if b['type']=='box' and not b['nav'] and 120<b['r'][2]<390 and 28<b['r'][3]<180 and b['r'][0]<=x+2 and b['r'][1]<=y+h/2 and b['r'][0]+b['r'][2]>=x+w-2 and b['r'][1]+b['r'][3]>=y+h/2]
        box=min(boxes,key=lambda b:b['r'][2]*b['r'][3]) if boxes else None
        bounds=box['r'] if box else [max(20,x-8),y-8,min(350,w+16),max(38,h+16)]
        if bounds[1]<45 or any(abs(f['r'][1]-bounds[1])<5 for f in frame['fields']):
            continue
        frame['fields'].append({'id':e['id'],'text':text,'r':bounds,'textRect':e['r'],'size':e['size'],'color':e['color'],'multiline':bounds[3]>70,'initial':text if explicit else '', 'search':text.lower().startswith('search ')})
    features[feature].append(frame)

for feature, scenes in features.items():
    (ROOT/f'assets/images/{feature}/design.json').write_text(json.dumps(scenes,ensure_ascii=False,separators=(',',':')))
    folder=ROOT/f'lib/features/{feature}'
    folder.mkdir(parents=True,exist_ok=True)
    cls=feature.title()+'Design'
    (folder/f'{feature}_design_overrides.dart').write_text(f'''// GENERATED by tools/figma/generate_specs.py. Do not edit measured values here.
/// Exact per-layer Figma colors, typography, spacing, borders and asset slots
/// are stored in [specAsset], indexed by original frame and node IDs.
abstract final class {cls} {{
  /// Figma: Ocean Project / High-Fidelity / {feature}; native widget specs.
  static const specAsset = 'assets/images/{feature}/design.json';
}}
''')
    notes=f'''# Design notes: {feature}

Source: Ocean Project, High-Fidelity. Original reference code is in `design_source/`.
Exact values and geometry are retained per Figma node in `{feature}_design_overrides.dart`'s spec asset.
The table below is a machine-generated spec table and design memory; values are never rounded to the nearest shared token.

| Frame | Node | Type | Exact Figma values / asset slot | Status |
|---|---|---|---|---|
'''
    for scene in scenes:
        for e in scene['elements']:
            style={k:v for k,v in e.items() if k not in ['ancestry','order','nav','name','text']}
            notes+=f"| {scene['id']} | {e['id']} | {e['type']} | `{json.dumps(style,ensure_ascii=False,separators=(',',':'))}` | Open |\n"
    notes+='\n## Assumptions\n\n- Prototype links navigate between native Flutter screens. Unspecified backend operations remain local previews.\n- The OS draws its status and home indicator bars. The app shell draws shared navigation.\n- Fixed illustrations retain their source geometry within a responsive, scrollable mobile column.\n\n## REQUEST\n\n- Review generated exact colors and typography for promotion to shared tokens.\n- Review source-design duplicates and typos before changing visible content.\n'
    (folder/'DESIGN_NOTES.md').write_text(notes)

catalog=[{k:s[k] for k in ['id','name','title','feature','width','height']} for s in frames]
(ROOT/'assets/images/map/screen_catalog.json').write_text(json.dumps(catalog,ensure_ascii=False))
(ROOT/'design_source/asset_audit.json').write_text(json.dumps(assets,indent=2))
print(json.dumps({'screens':len(frames),'features':{f:len(s) for f,s in features.items()},'assets':len(assets),'hotspots':sum(len(s['hotspots']) for s in frames),'fields':sum(len(s['fields']) for s in frames)}))
